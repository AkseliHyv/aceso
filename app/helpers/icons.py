def draw_arrow(oled, x, y, direction, size=2, color=1):
    """
    Draw a small triangular arrow.

    x, y = tip of the arrow
    direction = 'left', 'right', 'up', 'down'
    size = controls triangle size
    """

    if direction == 'left':
        oled.line(x + size, y - size, x, y, color)
        oled.line(x, y, x + size, y + size, color)
        oled.line(x + size, y - size, x + size, y + size, color)

    elif direction == 'right':
        oled.line(x - size, y - size, x, y, color)
        oled.line(x, y, x - size, y + size, color)
        oled.line(x - size, y - size, x - size, y + size, color)

    elif direction == 'up':
        oled.line(x - size, y + size, x, y, color)
        oled.line(x, y, x + size, y + size, color)
        oled.line(x - size, y + size, x + size, y + size, color)

    elif direction == 'down':
        oled.line(x - size, y - size, x, y, color)
        oled.line(x, y, x + size, y - size, color)
        oled.line(x - size, y - size, x + size, y - size, color)

def draw_circle(oled, x, y, size=2, color=1):
    """
    Draw a circle outline.
    x, y  = center
    size  = radius in pixels
    """
    oled.ellipse(x, y, size, size, color)

